export function localizeAnalysisText(locale: Locale, text: string): string {
  if (locale === "en" || !text) return text;
  const exact = analysisExact[text] ?? Object.entries(analysisExact).find(([key]) => key.toLowerCase() === text.toLowerCase())?.[1];
  if (exact) return exact;
  const t = (key: string, values?: TranslationValues) => translate(locale, key, values);
  const projectSummary = Object.keys(analysisExact).find((key) => ["Frontend application", "Backend API", "Full-stack application", "Library or package", "CLI", "Mobile application", "Monorepo", "Unclear"].includes(key) && text.startsWith(`${key}. `));
  if (projectSummary) {
    const details = text.slice(projectSummary.length + 2).replace(/\.$/, "").split(" and ").map((item) => localizeAnalysisText(locale, item)).join(" و");
    return `${analysisExact[projectSummary]}. ${details}.`;
  }

  const replacements: Array<[RegExp, (...matches: string[]) => string]> = [
    [/^Repository archive contains more than (.+) entries\.$/, (_all, count) => `يحتوي أرشيف المستودع على أكثر من ${count} إدخال.`],
    [/^Repository contains more than (.+) files\.$/, (_all, count) => `يحتوي المستودع على أكثر من ${count} ملف.`],
    [/^Repository archive returned HTTP (.+)\.$/, (_all, status) => `أرجع أرشيف المستودع حالة HTTP ${status}.`],
    [/^Biggest resolved drop-off is (.+) → (.+): (.+)% of candidates with a recorded outcome ended there\.$/, (_all, from, to, rate) => `أكبر تسرب محسوم هو ${translate(locale, from)} ← ${translate(locale, to)}: انتهى ${rate}% من المرشحين ذوي النتيجة المسجلة هناك.`],
    [/^(.+) is your strongest channel — (.+)% of its candidates get hired\.$/, (_all, source, rate) => `${translate(locale, source)} هي أقوى قناة لديك؛ تم توظيف ${rate}% من مرشحيها.`],
    [/^Candidates with strong or good code evidence have an observed hire rate (.+) times that of candidates with lighter signals in the current dataset\.$/, (_all, factor) => `لدى المرشحين بأدلة كود قوية أو جيدة معدل توظيف مرصود يبلغ ${factor} ضعف معدل المرشحين بإشارات أخف في البيانات الحالية.`],
    [/^Time-to-hire improved by (.+) days since (.+)\.$/, (_all, days, month) => `تحسن وقت التوظيف بمقدار ${days} يوم منذ ${month}.`],
    [/^Time-to-hire slowed by (.+) days since (.+)\.$/, (_all, days, month) => `تباطأ وقت التوظيف بمقدار ${days} يوم منذ ${month}.`],
    [/^A (.+) hosted in (.+)\.$/, (_all, type, repository) => `مشروع من نوع ${Object.entries(analysisExact).find(([key]) => key.toLowerCase() === type.toLowerCase())?.[1] ?? type} مستضاف في ${repository}.`],
    [/^Deterministic inspection identifies a (.+) using (.+)\.$/, (_all, type, technologies) => `يحدد الفحص الحتمي مشروعاً من نوع ${Object.entries(analysisExact).find(([key]) => key.toLowerCase() === type.toLowerCase())?.[1] ?? type} يستخدم ${technologies}.`],
    [/^(.+) is present \((.+)\)\.$/, (_all, technology, evidence) => `${technology} موجود (${evidence}).`],
    [/^(.+) implementation depth$/, (_all, skill) => `عمق تنفيذ ${skill}`],
    [/^(.+) is supported by deterministic repository signals\. (.+)$/, (_all, skill, method) => `${skill} مدعوم بإشارات حتمية من المستودع. ${localizeAnalysisText(locale, method)}`],
    [/^(.+) signal detected here\.$/, (_all, skill) => `تم اكتشاف إشارة ${skill} هنا.`],
    [/^(.+) is backed by repeated meaningful implementation rather than a dependency declaration\.$/, (_all, level) => `${analysisExact[level] ?? translate(locale, level)} مدعومة بتنفيذ فعلي متكرر وليس بمجرد تعريف اعتماد.`],
    [/^The selected evidence contains limited or no automated test implementation\.$/, () => "تحتوي الأدلة المحددة على تنفيذ محدود أو معدوم للاختبارات الآلية."],
    [/^The selected evidence contains limited explicit security or authorization handling\.$/, () => "تحتوي الأدلة المحددة على معالجة صريحة محدودة للأمان أو التفويض."],
    [/^The selected evidence contains limited observability, tracing, or structured logging signals\.$/, () => "تحتوي الأدلة المحددة على إشارات محدودة للمراقبة أو التتبع أو السجلات المنظمة."],
    [/^The selected evidence contains limited deployment or infrastructure configuration\.$/, () => "تحتوي الأدلة المحددة على إعدادات محدودة للنشر أو البنية التحتية."],
    [/^The selected evidence contains limited explicit error-handling examples\.$/, () => "تحتوي الأدلة المحددة على أمثلة صريحة محدودة لمعالجة الأخطاء."],
    [/^The selected evidence contains limited project documentation\.$/, () => "تحتوي الأدلة المحددة على توثيق محدود للمشروع."],
    [/^The selected evidence contains limited explicit accessibility implementation\.$/, () => "تحتوي الأدلة المحددة على تنفيذ صريح محدود لإمكانية الوصول."],
    [/^The selected evidence contains limited explicit performance-oriented implementation\.$/, () => "تحتوي الأدلة المحددة على تنفيذ صريح محدود موجه للأداء."],
    [/^At least three meaningful implementation files across multiple areas, plus tests or multiple architectural boundaries\.$/, () => "ثلاثة ملفات تنفيذ فعلية على الأقل عبر مناطق متعددة، إضافة إلى اختبارات أو حدود معمارية متعددة."],
    [/^At least two meaningful implementation files or repeated non-trivial use across modules\.$/, () => "ملفا تنفيذ فعليان على الأقل أو استخدام متكرر غير بسيط عبر الوحدات."],
    [/^One meaningful implementation example or narrow test-backed use\.$/, () => "مثال تنفيذ فعلي واحد أو استخدام محدود مدعوم باختبار."],
    [/^Dependency, manifest, configuration, documentation, or trivial usage signals only\.$/, () => "إشارات اعتماد أو تعريف أو إعداد أو توثيق أو استخدام بسيط فقط."],
    [/^No grounded implementation evidence remains\.$/, () => "لا توجد أدلة تنفيذ مدعومة متبقية."],
    [/^(.+) is supported by reviewed implementation evidence in this repository\.$/, (_all, claim) => `${claim} مدعوم بأدلة تنفيذ تمت مراجعتها في هذا المستودع.`],
    [/^(.+) is supported by repository signals, though this analysis does not verify the full scope of the résumé claim\.$/, (_all, claim) => `${claim} مدعوم بإشارات من المستودع، لكن هذا التحليل لا يتحقق من النطاق الكامل لادعاء السيرة.`],
    [/^Some related implementation evidence is visible, but the complete claim cannot be verified from this repository alone\.$/, () => "تظهر بعض أدلة التنفيذ ذات الصلة، لكن لا يمكن التحقق من الادعاء كاملاً من هذا المستودع وحده."],
    [/^(.+) has no repository evidence in the selected files\. This repository does not provide enough evidence to verify or reject the claim\.$/, (_all, claim) => `لا يملك ${claim} أدلة مستودع في الملفات المحددة. لا يوفر هذا المستودع أدلة كافية للتحقق من الادعاء أو رفضه.`],
    [/^Pick a behavior covered (?:in|by) (.+)\. What regression does the test protect against, and which important failure path is still missing\?$/, (_all, file) => `اختر سلوكاً يغطيه ${file}. ما الخلل الذي يمنع الاختبار عودته، وما مسار الفشل المهم الذي لا يزال مفقوداً؟`],
    [/^(.+) appears in (.+)\. Show the implementation decision it supports here, then compare it with one reasonable alternative for this codebase\.$/, (_all, technology, file) => `تظهر ${technology} في ${file}. وضّح قرار التنفيذ الذي تدعمه هنا، ثم قارنه ببديل مناسب لهذا المشروع.`],
    [/^Walk through the responsibility of (.+)\. Which edge case or scaling pressure would make you change this implementation first\?$/, (_all, file) => `اشرح مسؤولية ${file}. ما الحالة الطرفية أو ضغط التوسع الذي سيدفعك لتغيير هذا التنفيذ أولاً؟`],
    [/^Trace one request through (.+)\. Where are inputs validated, responses shaped, and failure cases converted into a stable API contract\?$/, (_all, file) => `تتبّع طلباً واحداً عبر ${file}. أين يتم التحقق من المدخلات وصياغة الاستجابات وتحويل حالات الفشل إلى عقد API ثابت؟`],
    [/^Walk through the trust boundary implemented (?:in|by) (.+)\. Which identity or permission assumptions are made, and how would you test a rejected request\?$/, (_all, file) => `اشرح حدود الثقة المنفذة في ${file}. ما افتراضات الهوية أو الصلاحيات، وكيف ستختبر طلباً مرفوضاً؟`],
    [/^Explain the persistence decision visible in (.+)\. How are data integrity, query failure, and schema evolution handled by the surrounding design\?$/, (_all, file) => `اشرح قرار التخزين الظاهر في ${file}. كيف يعالج التصميم سلامة البيانات وفشل الاستعلام وتطور المخطط؟`],
    [/^(.+) contains repository-backed persistence logic\. How would you handle connection pooling, transaction boundaries, and query failures around this implementation\?$/, (_all, subject) => `يحتوي ${subject} على منطق تخزين مدعوم بالمستودع. كيف ستعالج تجميع الاتصالات وحدود المعاملات وفشل الاستعلامات حول هذا التنفيذ؟`],
    [/^Use (.+) to explain the state lifecycle: who owns it, which code may change it, and how stale or invalid state is prevented\.$/, (_all, file) => `استخدم ${file} لشرح دورة حياة الحالة: من يملكها، وأي كود يغيرها، وكيف تُمنع الحالة القديمة أو غير الصالحة؟`],
    [/^Trace an error path in (.+) from failure to caller-visible behavior\. What is recovered, logged, retried, or deliberately allowed to fail\?$/, (_all, file) => `تتبّع مسار خطأ في ${file} من الفشل إلى السلوك الظاهر للمستدعي. ما الذي يُسترد أو يُسجل أو يُعاد أو يُترك ليفشل عمداً؟`],
    [/^Use (.+) to explain where this responsibility sits in the system\. Which dependency direction does it enforce, and what would break if this boundary moved\?$/, (_all, subject) => `استخدم ${subject} لشرح موقع هذه المسؤولية في النظام. ما اتجاه الاعتماد الذي تفرضه، وما الذي سيتعطل إذا نُقلت هذه الحدود؟`],
    [/^Use (.+) to explain what production failure would be visible to the team\. Which diagnostic context is captured, and what remains opaque\?$/, (_all, subject) => `استخدم ${subject} لشرح فشل الإنتاج الذي سيكون مرئياً للفريق. ما السياق التشخيصي المسجل، وما الذي يبقى غامضاً؟`],
    [/^Starting at (.+), map the handoff to the next module or external boundary\. Which coupling is intentional, and where would you introduce an interface if the system grew\?$/, (_all, subject) => `بدءاً من ${subject}، ارسم انتقال المسؤولية إلى الوحدة التالية أو الحدود الخارجية. أي ترابط مقصود، وأين ستضيف واجهة إذا توسع النظام؟`],
    [/^Why ask this: (.+) The concrete symbol (.+) and the cited files triggered this prompt\.$/, (_all, summary, symbol) => `لماذا يُطرح هذا السؤال؟ ${localizeAnalysisText(locale, summary)} الرمز الفعلي ${symbol} والملفات المذكورة هما سبب هذا السؤال.`],
    [/^Why ask this: (.+) The cited implementation files triggered this prompt\.$/, (_all, summary) => `لماذا يُطرح هذا السؤال؟ ${localizeAnalysisText(locale, summary)} ملفات التنفيذ المذكورة هي سبب هذا السؤال.`],
    [/^Why ask this: grounded in meaningful (.+) usage selected from the cited implementation file, not the dependency list alone\.$/, (_all, technology) => `لماذا يُطرح هذا السؤال؟ لأنه يستند إلى استخدام فعلي لـ ${technology} في ملف التنفيذ المذكور، لا إلى قائمة الاعتمادات وحدها.`],
    [/^Why ask this: grounded in the cited (.+) selected from the repository\.$/, (_all, reason) => `لماذا يُطرح هذا السؤال؟ لأنه يستند إلى ${localizeAnalysisText(locale, reason)} مذكور ومحدد من المستودع.`],
    [/^Why ask this: the prompt uses boundary files identified by deterministic path analysis\.$/, () => "لماذا يُطرح هذا السؤال؟ لأنه يستخدم ملفات الحدود التي حددها التحليل الحتمي لمسارات المستودع."],
    [/^(.+); meaningful usage is evaluated by file role and content depth\.$/, (_all, reason) => `${localizeAnalysisText(locale, reason)}؛ يُقيَّم الاستخدام الفعلي حسب دور الملف وعمق محتواه.`],
    [/^(.+) with (\d+) grounded skill signals?\.$/, (_all, type, count) => `${localizeAnalysisText(locale, type)} مع ${count} من إشارات المهارات المدعومة.`],
    [/^(.+) The cited files are the repository evidence for this prompt\.$/, (_all, summary) => `${localizeAnalysisText(locale, summary)} الملفات المذكورة هي دليل المستودع لهذا السؤال.`],
    [/^Grounded in meaningful (.+) usage selected from the repository, not the dependency list alone\.$/, (_all, technology) => `يستند إلى استخدام فعلي لـ ${technology} محدد من المستودع، لا إلى قائمة الاعتمادات وحدها.`],
    [/^Grounded in a selected representative source file\.$/, () => "يستند إلى ملف مصدر تمثيلي محدد."],
  ];
  for (const [pattern, replacement] of replacements) {
    const match = text.match(pattern);
    if (match) return replacement(...match);
  }
  // A known label with a trailing full stop (e.g. a project type used as a sentence).
  const sentence = text.replace(/\.$/, "");
  if (sentence !== text && analysisExact[sentence]) return `${analysisExact[sentence]}.`;
  return t(text);
}
